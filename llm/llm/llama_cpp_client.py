"""
Reusable, modular client for communicating with a local llama.cpp HTTP server.

Features:
- Health checking and server status reporting.
- Standard chat completion and single-prompt generation using the official
  llama.cpp OpenAI-compatible API (/v1/chat/completions).
- Streaming support with Time-To-First-Token (TTFT) measurement.
- Latency and tokens-per-second performance metrics (with clear distinction
  between runtime-reported metrics vs. client-calculated metrics).
- Qwen3 thinking handling: parses <think>...</think> blocks when present
  while strictly preserving raw output without alteration.
- Robust error handling for timeouts, connection errors, and server errors.
- Clean separation of concerns, suitable for FastAPI or CLI tools.
"""

from __future__ import annotations

import json
import logging
import re
import time
from dataclasses import dataclass, field
from typing import Any, Dict, Iterator, List, Optional

import httpx

from llm.model_config import GenerationConfig, ModelConfig

logger = logging.getLogger("llm.llama_cpp_client")


# ============================================================================
# Exception Hierarchy
# ============================================================================

class LlamaCppError(Exception):
    """Base exception for all llama.cpp client errors."""
    pass


class LlamaCppConnectionError(LlamaCppError):
    """Raised when the client cannot establish a connection to the local server."""
    pass


class LlamaCppTimeoutError(LlamaCppError):
    """Raised when a connection or generation request times out."""
    pass


class LlamaCppInvalidResponseError(LlamaCppError):
    """Raised when the server returns a 4xx error or an unparseable response."""
    pass


class LlamaCppServerError(LlamaCppError):
    """Raised when the server returns a 5xx internal error."""
    pass


# ============================================================================
# Data Classes
# ============================================================================

@dataclass
class GenerationResult:
    """Represents the complete result of a generation request."""

    content: str
    """Full raw response generated by the model. Never altered or stripped."""

    thinking: Optional[str] = None
    """Extracted reasoning text if <think>...</think> tags were present."""

    text_without_thinking: Optional[str] = None
    """Extracted text after removing <think>...</think> tags (if present)."""

    prompt_tokens: Optional[int] = None
    """Number of tokens in the prompt, if reported by the runtime."""

    completion_tokens: Optional[int] = None
    """Number of generated tokens, if reported by the runtime."""

    total_tokens: Optional[int] = None
    """Total tokens (prompt + completion), if reported by the runtime."""

    elapsed_seconds: float = 0.0
    """Total generation round-trip time in seconds measured by the client."""

    tokens_per_second: Optional[float] = None
    """Generation speed in tokens per second."""

    metrics_source: str = "unavailable"
    """Source of performance metrics: 'runtime', 'calculated', or 'unavailable'."""

    model_name: str = ""
    """Model identifier reported or configured."""

    finish_reason: Optional[str] = None
    """Reason for completion finishing (e.g. 'stop', 'length')."""

    raw_response: Optional[Dict[str, Any]] = field(default=None, repr=False)
    """Raw JSON dictionary returned by the server."""


@dataclass
class StreamChunk:
    """Represents an individual token or text chunk emitted during streaming."""

    delta: str
    """Incremental text produced in this chunk."""

    cumulative_text: str
    """Accumulated text generated up to and including this chunk."""

    is_first_token: bool = False
    """True if this is the first non-empty text chunk emitted."""

    time_to_first_token: Optional[float] = None
    """Elapsed seconds from request start to the first token."""

    elapsed_seconds: float = 0.0
    """Elapsed seconds since request start."""

    finish_reason: Optional[str] = None
    """Finish reason if this chunk is the final completion chunk."""

    usage: Optional[Dict[str, Any]] = None
    """Usage data if provided in this chunk."""


# ============================================================================
# Client Implementation
# ============================================================================

class LlamaCppClient:
    """Client for interacting with a local llama.cpp HTTP server.

    Connects to the server's OpenAI-compatible endpoints (/v1/chat/completions)
    and native monitoring endpoints (/health, /props).
    """

    def __init__(self, config: Optional[ModelConfig] = None) -> None:
        """Initialize the client.

        Args:
            config: Central ModelConfig instance. If omitted, loaded from environment.
        """
        self.config = config or ModelConfig.from_env()
        base_url = self.config.client.base_url.rstrip("/")
        if base_url.endswith("/v1"):
            base_url = base_url[:-3]
        self._base_url = base_url

        headers = {"Content-Type": "application/json"}
        if self.config.client.api_key:
            headers["Authorization"] = f"Bearer {self.config.client.api_key.get_secret_value()}"

        timeout = httpx.Timeout(
            connect=self.config.client.connect_timeout,
            read=self.config.client.generation_timeout,
            write=self.config.client.connect_timeout,
            pool=self.config.client.connect_timeout,
        )

        self._http_client = httpx.Client(
            base_url=self._base_url,
            headers=headers,
            timeout=timeout,
        )

    def close(self) -> None:
        """Close the underlying HTTP client connection pool."""
        self._http_client.close()

    def __enter__(self) -> LlamaCppClient:
        return self

    def __exit__(self, exc_type, exc_val, exc_tb) -> None:
        self.close()

    # ------------------------------------------------------------------------
    # Health and Status Checks
    # ------------------------------------------------------------------------

    def check_health(self) -> Dict[str, Any]:
        """Check whether the local llama.cpp server is reachable and ready.

        Returns:
            Dict containing reachability and health status details.

        Raises:
            LlamaCppConnectionError: If the server cannot be reached.
            LlamaCppTimeoutError: If the health check times out.
            LlamaCppServerError: If the server returns 5xx error.
        """
        try:
            resp = self._http_client.get("/health")
            if resp.status_code == 200:
                try:
                    data = resp.json()
                except Exception:
                    data = {"status": "ok"}
                return {"reachable": True, "status_code": 200, "details": data}
            elif resp.status_code == 503:
                # llama-server returns 503 while the model is still loading
                return {
                    "reachable": True,
                    "status_code": 503,
                    "status": "loading",
                    "details": resp.text,
                }
            else:
                raise LlamaCppServerError(
                    f"Health check returned unexpected HTTP {resp.status_code}: {resp.text}"
                )
        except httpx.ConnectError as err:
            raise LlamaCppConnectionError(
                f"Could not connect to llama.cpp server at {self._base_url}. "
                "Ensure llama-server is running."
            ) from err
        except httpx.TimeoutException as err:
            raise LlamaCppTimeoutError(
                f"Health check timed out after {self.config.client.connect_timeout}s."
            ) from err

    def is_healthy(self) -> bool:
        """Return True if the server responds with HTTP 200, False otherwise."""
        try:
            health = self.check_health()
            return health.get("status_code") == 200
        except Exception:
            return False

    def get_status(self) -> Dict[str, Any]:
        """Retrieve model and server runtime status from llama.cpp.

        Combines /health and /v1/models (or /props) if available.
        """
        health_info = self.check_health()
        status_info: Dict[str, Any] = {
            "health": health_info,
            "configured_model": self.config.server_launch.model_name,
            "base_url": self._base_url,
        }

        # Try /v1/models
        try:
            resp = self._http_client.get("/v1/models")
            if resp.status_code == 200:
                models_data = resp.json()
                status_info["models"] = models_data.get("data", [])
        except Exception:
            status_info["models"] = []

        # Try /props if enabled on server
        try:
            resp = self._http_client.get("/props")
            if resp.status_code == 200:
                status_info["props"] = resp.json()
        except Exception:
            pass

        return status_info

    # ------------------------------------------------------------------------
    # Generation: Non-Streaming
    # ------------------------------------------------------------------------

    def chat(
        self,
        messages: List[Dict[str, str]],
        override_config: Optional[GenerationConfig] = None,
    ) -> GenerationResult:
        """Send chat messages to the server and return the generated completion.

        Args:
            messages: List of message dictionaries with 'role' and 'content' keys.
            override_config: Optional GenerationConfig to override default settings.

        Returns:
            GenerationResult containing generated text, thinking extract, and metrics.

        Raises:
            LlamaCppConnectionError: On network connection failure.
            LlamaCppTimeoutError: On request timeout.
            LlamaCppInvalidResponseError: On 4xx response or invalid format.
            LlamaCppServerError: On 5xx server error.
        """
        if not messages:
            raise ValueError("Messages list cannot be empty.")

        gen_cfg = override_config or self.config.generation
        payload = self._build_chat_payload(messages, gen_cfg, stream=False)

        start_time = time.perf_counter()
        response = None
        for attempt in range(2):
            try:
                response = self._http_client.post("/v1/chat/completions", json=payload)
                break
            except httpx.ConnectError as err:
                raise LlamaCppConnectionError(
                    f"Connection failed to {self._base_url}/v1/chat/completions. "
                    "Ensure llama-server is running."
                ) from err
            except httpx.TimeoutException as err:
                raise LlamaCppTimeoutError(
                    f"Generation timed out after {self.config.client.generation_timeout}s."
                ) from err
            except httpx.HTTPError as err:
                if attempt == 0 and ("10054" in str(err) or isinstance(err, httpx.RemoteProtocolError)):
                    logger.debug("Retrying request after stale keepalive connection closed by llama-server.")
                    continue
                raise LlamaCppConnectionError(f"HTTP error during generation: {err}") from err

        elapsed_seconds = time.perf_counter() - start_time

        if response.status_code == 400:
            raise LlamaCppInvalidResponseError(
                f"Server rejected request (HTTP 400): {response.text}"
            )
        elif response.status_code >= 500:
            raise LlamaCppServerError(
                f"Server error during generation (HTTP {response.status_code}): {response.text}"
            )
        elif response.status_code != 200:
            raise LlamaCppInvalidResponseError(
                f"Unexpected status code {response.status_code}: {response.text}"
            )

        try:
            data = response.json()
        except Exception as err:
            raise LlamaCppInvalidResponseError("Failed to parse server response as JSON.") from err

        return self._parse_chat_response(data, elapsed_seconds)

    def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        override_config: Optional[GenerationConfig] = None,
    ) -> GenerationResult:
        """Convenience method to generate text from a single prompt string.

        Args:
            prompt: User prompt.
            system_prompt: Optional system prompt to instruct model behavior.
            override_config: Optional generation parameters override.

        Returns:
            GenerationResult instance.
        """
        messages: List[Dict[str, str]] = []
        if system_prompt:
            messages.append({"role": "system", "content": system_prompt})
        messages.append({"role": "user", "content": prompt})

        return self.chat(messages=messages, override_config=override_config)

    # ------------------------------------------------------------------------
    # Generation: Streaming
    # ------------------------------------------------------------------------

    def stream_chat(
        self,
        messages: List[Dict[str, str]],
        override_config: Optional[GenerationConfig] = None,
    ) -> Iterator[StreamChunk]:
        """Stream chat completion chunks from the local server.

        Yields:
            StreamChunk instances as tokens arrive. Measures TTFT on first token.

        Raises:
            LlamaCppConnectionError: On connection failure.
            LlamaCppTimeoutError: On read timeout.
            LlamaCppServerError: On server error.
        """
        if not messages:
            raise ValueError("Messages list cannot be empty.")

        gen_cfg = override_config or self.config.generation
        payload = self._build_chat_payload(messages, gen_cfg, stream=True)

        start_time = time.perf_counter()
        first_token_time: Optional[float] = None
        accumulated_text = ""
        is_first = True

        try:
            with self._http_client.stream("POST", "/v1/chat/completions", json=payload) as response:
                if response.status_code != 200:
                    resp_body = response.read().decode("utf-8", errors="replace")
                    if response.status_code >= 500:
                        raise LlamaCppServerError(
                            f"Server error during streaming (HTTP {response.status_code}): {resp_body}"
                        )
                    raise LlamaCppInvalidResponseError(
                        f"Stream request failed (HTTP {response.status_code}): {resp_body}"
                    )

                for line in response.iter_lines():
                    if not line:
                        continue
                    line = line.strip()
                    if not line.startswith("data:"):
                        continue

                    data_str = line[len("data:"):].strip()
                    if data_str == "[DONE]":
                        break

                    try:
                        chunk_dict = json.loads(data_str)
                    except json.JSONDecodeError:
                        continue

                    choices = chunk_dict.get("choices", [])
                    delta_text = ""
                    finish_reason = None
                    if choices:
                        delta = choices[0].get("delta", {})
                        delta_text = delta.get("content", "")
                        finish_reason = choices[0].get("finish_reason")

                    now = time.perf_counter()
                    ttft = None
                    first_flag = False

                    if delta_text:
                        if is_first:
                            first_token_time = now - start_time
                            ttft = first_token_time
                            first_flag = True
                            is_first = False
                        accumulated_text += delta_text

                    yield StreamChunk(
                        delta=delta_text,
                        cumulative_text=accumulated_text,
                        is_first_token=first_flag,
                        time_to_first_token=ttft,
                        elapsed_seconds=now - start_time,
                        finish_reason=finish_reason,
                        usage=chunk_dict.get("usage"),
                    )

        except httpx.ConnectError as err:
            raise LlamaCppConnectionError(
                f"Connection failed to {self._base_url}/v1/chat/completions."
            ) from err
        except httpx.TimeoutException as err:
            raise LlamaCppTimeoutError(
                f"Streaming timed out after {self.config.client.generation_timeout}s."
            ) from err

    def stream_generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        override_config: Optional[GenerationConfig] = None,
    ) -> Iterator[StreamChunk]:
        """Convenience method to stream response for a single prompt."""
        messages: List[Dict[str, str]] = []
        if system_prompt:
            messages.append({"role": "system", "content": system_prompt})
        messages.append({"role": "user", "content": prompt})
        return self.stream_chat(messages=messages, override_config=override_config)

    # ------------------------------------------------------------------------
    # Internal Helpers
    # ------------------------------------------------------------------------

    def _build_chat_payload(
        self,
        messages: List[Dict[str, str]],
        gen_cfg: GenerationConfig,
        stream: bool,
    ) -> Dict[str, Any]:
        """Construct the request body for /v1/chat/completions."""
        payload: Dict[str, Any] = {
            "model": self.config.server_launch.model_name,
            "messages": messages,
            "temperature": gen_cfg.temperature,
            "top_p": gen_cfg.top_p,
            "max_tokens": gen_cfg.max_tokens,
            "stream": stream,
        }

        # Qwen3 / template thinking control:
        # If enable_thinking is explicitly configured, pass it in chat_template_kwargs
        if gen_cfg.enable_thinking is not None:
            payload["chat_template_kwargs"] = {
                "enable_thinking": gen_cfg.enable_thinking
            }

        # If reasoning_budget is specified (llama-server extension):
        if gen_cfg.reasoning_budget is not None:
            payload["reasoning_budget"] = gen_cfg.reasoning_budget

        # Include any extra custom parameters
        if gen_cfg.extra_params:
            payload.update(gen_cfg.extra_params)

        return payload

    def _parse_chat_response(
        self,
        data: Dict[str, Any],
        elapsed_seconds: float,
    ) -> GenerationResult:
        """Parse the JSON response returned by /v1/chat/completions."""
        choices = data.get("choices", [])
        if not choices:
            raise LlamaCppInvalidResponseError(
                "Invalid response format: 'choices' field is empty or missing."
            )

        message = choices[0].get("message", {})
        raw_content = message.get("content", "")
        finish_reason = choices[0].get("finish_reason")
        model_name = data.get("model", self.config.server_launch.model_name)

        # Parse Qwen3 <think>...</think> tags if present
        thinking, text_without_thinking = self._extract_thinking(raw_content)

        # Token usage parsing
        usage = data.get("usage", {})
        prompt_tokens = usage.get("prompt_tokens")
        completion_tokens = usage.get("completion_tokens")
        total_tokens = usage.get("total_tokens")

        # Performance metrics
        tokens_per_sec = None
        metrics_source = "unavailable"

        # Check if llama.cpp provided native timings
        timings = data.get("timings", {})
        if "predicted_per_second" in timings and timings["predicted_per_second"] is not None:
            tokens_per_sec = float(timings["predicted_per_second"])
            metrics_source = "runtime"
        elif completion_tokens is not None and elapsed_seconds > 0:
            tokens_per_sec = round(completion_tokens / elapsed_seconds, 2)
            metrics_source = "calculated"

        return GenerationResult(
            content=raw_content,
            thinking=thinking,
            text_without_thinking=text_without_thinking,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            elapsed_seconds=round(elapsed_seconds, 4),
            tokens_per_second=tokens_per_sec,
            metrics_source=metrics_source,
            model_name=model_name,
            finish_reason=finish_reason,
            raw_response=data,
        )

    @staticmethod
    def _extract_thinking(text: str) -> tuple[Optional[str], Optional[str]]:
        """Extract thinking reasoning from <think>...</think> tags.

        Returns:
            Tuple of (thinking_content, text_without_thinking).
            If no <think> tags are present, returns (None, None).
        """
        if "<think>" not in text:
            return None, None

        match = re.search(r"<think>(.*?)(?:</think>|$)", text, flags=re.DOTALL)
        if not match:
            return None, None

        thinking = match.group(1).strip()
        text_without_thinking = re.sub(
            r"<think>.*?</think>\s*", "", text, flags=re.DOTALL
        ).strip()

        return thinking, text_without_thinking

