"""
Retrieval-Augmented Generation (RAG) pipeline for the PLC Simulator AI Assistant.

Integrates the PostgreSQL + pgvector retriever with the existing local llama.cpp
LLM client to provide grounded, citation-backed answers to PLC programming questions.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from llm.llama_cpp_client import GenerationResult, LlamaCppClient
from llm.model_config import GenerationConfig
from rag.config import RAGConfig
from rag.retriever import DocumentRetriever, RetrievedChunk

logger = logging.getLogger("rag.pipeline")

SYSTEM_PROMPT = """You are an expert technical assistant and tutor for industrial automation, PLC programming, and electrical control systems inside the PLC Studio simulator.

Answer questions using the provided simulator runtime context, the authoritative documentation passages supplied in the prompt, and standard industrial automation engineering principles.

CRITICAL INSTRUCTIONS:
1. General Automation Concepts & Definitions:
   - When asked foundational questions (e.g., what is a PLC, what is a scan cycle, what is ladder logic, inputs vs. outputs, normally open/closed contacts, timers, memory areas):
   - Provide a clear, comprehensive, and educational explanation.
   - Ground and contextualize the explanation within the active controller family (e.g. Siemens S7-1200 / SIMATIC S7, or Rockwell Logix 5000) and reference relevant concepts from the supplied documentation (e.g. cyclic program execution OB1, process image inputs/outputs, PLC tags).
   - NEVER refuse to answer or output boilerplate stating "the indexed documentation does not establish this answer" for standard industrial automation concepts, terminology, or definitions.
2. Simulator Runtime Context & Ladder Logic:
   - When the user asks to explain their ladder logic, check wiring, diagnose live I/O states, or troubleshoot machine behavior:
   - Directly inspect and explain the ladder networks, rungs, and hardware components provided in [SIMULATOR RUNTIME CONTEXT].
   - Walk through each network sequentially from left to right, explaining how contacts conduct (e.g. NO contacts passing power when high/1, NC contacts passing power when low/0) and how coils/bits are driven.
   - Explain how hardware parts connect to the PLC addresses (e.g. %I0.0, %Q0.0), and report their live states if present.
   - Use the retrieved documentation passages as authoritative technical reference for instruction behavior and standards.
3. Platform-Specific Grounding:
   - Ground technical claims about instruction standards, memory structures, and controller specifications in the supplied documentation. Do not invent non-existent instruction behavior, operands, or manual references.
   - Respect the manufacturer, controller family (e.g. Siemens S7-1200 vs Rockwell Logix 5000), programming environment (TIA Portal / STEP 7 vs Studio 5000), and terminology established by the context. Never confuse or interchange instruction semantics between different PLC platforms.
4. Unsupported Obscure Inquiries:
   - Only if the user asks for a specific, proprietary hardware specification, unlisted wiring pinout, or catalog part number that is neither in the supplied documentation nor standard engineering knowledge, state that the specific detail is not found in the indexed manual passages and suggest where in the manual or hardware catalog to look.
5. Tone and Style:
   - Keep answers concise, technically precise, educational, and easy for students and automation engineers to follow.
"""

@dataclass
class Citation:
    """Represents a validated citation to a source manual."""

    document_title: str
    publication_number: str
    page_number: int
    end_page_number: int

    def __str__(self) -> str:
        page_str = (
            f"p. {self.page_number}"
            if self.page_number == self.end_page_number or not self.end_page_number
            else f"pp. {self.page_number}-{self.end_page_number}"
        )
        if self.publication_number:
            return f"{self.document_title} ({self.publication_number}), {page_str}"
        return f"{self.document_title}, {page_str}"


@dataclass
class RAGAnswer:
    """Complete response returned by the RAG pipeline."""

    answer: str
    """Grounded answer generated by the model."""

    citations: List[Citation]
    """Authoritative citations from retrieved passages."""

    retrieved_chunks: List[RetrievedChunk]
    """Passages retrieved from the knowledge base."""

    latency_seconds: float = 0.0
    """Total response generation latency in seconds."""

    tokens_per_second: Optional[float] = None
    """Generation speed in tokens per second."""

    metrics_source: str = "unavailable"
    """Source of performance metrics ('runtime', 'calculated', or 'unavailable')."""

    raw_llm_result: Optional[GenerationResult] = field(default=None, repr=False)
    """Underlying GenerationResult from LlamaCppClient."""


class RAGPipeline:
    """Executes the complete retrieval and question-answering workflow."""

    def __init__(
        self,
        retriever: Optional[DocumentRetriever] = None,
        llm_client: Optional[LlamaCppClient] = None,
        config: Optional[RAGConfig] = None,
    ) -> None:
        """Initialize the RAG pipeline.

        Args:
            retriever: Optional DocumentRetriever instance.
            llm_client: Optional LlamaCppClient instance (reuses existing LLM layer).
            config: Optional RAGConfig instance.
        """
        self.config = config or RAGConfig.from_env()
        self.retriever = retriever or DocumentRetriever(config=self.config)
        self.llm_client = llm_client or LlamaCppClient()

    def answer_question(
        self,
        question: str,
        simulator_context: Optional[Dict[str, Any]] = None,
        top_k: Optional[int] = None,
        threshold: Optional[float] = None,
        override_gen_config: Optional[GenerationConfig] = None,
    ) -> RAGAnswer:
        """Answer a user query with retrieved documentation passages and simulator context.

        Args:
            question: User's technical query.
            simulator_context: Optional context from simulator frontend.
            top_k: Max chunks to retrieve.
            threshold: Minimum similarity threshold.
            override_gen_config: Optional GenerationConfig overrides.

        Returns:
            RAGAnswer dataclass instance.
        """
        clean_q = question.strip()
        if not clean_q:
            raise ValueError("Question cannot be empty.")

        # Determine target platform filter and augmented retrieval query
        doc_filter: Optional[str] = None
        platform_name = ""
        keywords: List[str] = []

        if simulator_context:
            model_name = str(simulator_context.get("controller_model") or "").lower()
            extra = simulator_context.get("extra_context") or {}
            if isinstance(extra, dict) and not model_name:
                model_name = str(extra.get("controller") or "").lower()

            if "siemens" in model_name or "s7" in model_name:
                doc_filter = "siemens"
                platform_name = "Siemens S7-1200"
            elif "rockwell" in model_name or "logix" in model_name or "allen" in model_name:
                doc_filter = "rockwell"
                platform_name = "Rockwell Logix 5000"

            supported = simulator_context.get("supported_instructions")
            if isinstance(supported, list) and supported:
                keywords.extend([str(x) for x in supported[:4]])

        # Extract target query for vector retrieval (strip out any prepended conversation labels)
        target_q = clean_q
        if "Current question:" in clean_q:
            target_q = clean_q.split("Current question:")[-1].strip()

        # Augment retrieval query if the user asks generic workbench, ladder, or conceptual questions
        augmented_query = target_q
        q_lower = target_q.lower()
        if any(term in q_lower for term in ("ladder", "logic", "wiring", "contact", "coil", "motor", "rung")):
            extra_terms: List[str] = []
            if platform_name and platform_name.lower() not in q_lower:
                extra_terms.append(platform_name)
            if "siemens" in platform_name.lower():
                extra_terms.extend(["LAD", "bit logic operations", "contact", "coil"])
            elif "rockwell" in platform_name.lower():
                extra_terms.extend(["ladder diagram", "bit instructions"])
            if keywords:
                extra_terms.extend(keywords)

            if extra_terms:
                augmented_query = f"{target_q} {' '.join(extra_terms)}"
        elif any(term in q_lower for term in ("what is plc", "what is a plc", "plc meaning", "explain plc", "plc concept", "introduction", "overview", "scan cycle")):
            extra_terms = []
            if platform_name and platform_name.lower() not in q_lower:
                extra_terms.append(platform_name)
            extra_terms.extend(["programmable logic controller", "system overview", "PLC concepts"])
            augmented_query = f"{target_q} {' '.join(extra_terms)}"

        # 1. Retrieve relevant documentation passages
        chunks = self.retriever.retrieve(
            query=augmented_query,
            top_k=top_k,
            threshold=threshold,
            document_filter=doc_filter,
        )

        # 3. Handle case where no relevant chunks pass similarity threshold
        if not chunks:
            logger.info(f"No passages met similarity threshold for query: '{clean_q[:50]}'")
            no_evidence_msg = (
                "The indexed documentation passages do not contain sufficient evidence to establish a grounded answer "
                f"for: '{clean_q}'.\n\n"
                "Try clarifying the PLC platform, controller family, instruction, "
                "or programming environment so the relevant documentation can be identified."
            )
            return RAGAnswer(
                answer=no_evidence_msg,
                citations=[],
                retrieved_chunks=[],
                latency_seconds=0.0,
            )

        # 4. Construct prompt with budgeted evidence and optional simulator context
        prompt_parts: List[str] = [
            "Use the following authoritative documentation passages to answer the question:\n"
        ]

        # Budget retrieved passages (~3200 chars ~ 800 tokens) to ensure prompt stays safely within context limit
        max_context_chars = 3200
        current_context_chars = 0
        used_chunks: List[RetrievedChunk] = []

        for c in chunks:
            chunk_len = len(c.content)
            if current_context_chars + chunk_len > max_context_chars and used_chunks:
                break
            used_chunks.append(c)
            current_context_chars += chunk_len
            prompt_parts.append(
                f"[DOCUMENT PASSAGE {len(used_chunks)}]\n"
                f"Source: {c.document_title} ({c.publication_number})\n"
                f"Page: {c.page_number}\n"
                f"Content:\n{c.content}\n"
            )

        # Extract citations from the passages actually used in the prompt
        citations: List[Citation] = []
        seen_citations = set()
        for c in used_chunks:
            key = (c.document_title, c.publication_number, c.page_number, c.end_page_number)
            if key not in seen_citations:
                seen_citations.add(key)
                citations.append(
                    Citation(
                        document_title=c.document_title,
                        publication_number=c.publication_number,
                        page_number=c.page_number,
                        end_page_number=c.end_page_number,
                    )
                )

        if simulator_context:
            prompt_parts.append(
                "[SIMULATOR RUNTIME CONTEXT]\n"
                "Note: The following represents the current state or supported feature set of the simulator:\n"
            )
            for k, v in simulator_context.items():
                prompt_parts.append(f"{k}: {v}\n")

        prompt_parts.append(f"QUESTION: {clean_q}\n\nANSWER:")
        user_prompt = "\n".join(prompt_parts)

        # 5. Generate answer using existing LlamaCppClient
        llm_result = self.llm_client.generate(
            prompt=user_prompt,
            system_prompt=SYSTEM_PROMPT,
            override_config=override_gen_config,
        )

        # 6. Format and return grounded result
        final_answer = llm_result.text_without_thinking or llm_result.content

        return RAGAnswer(
            answer=final_answer,
            citations=citations,
            retrieved_chunks=used_chunks,
            latency_seconds=llm_result.elapsed_seconds,
            tokens_per_second=llm_result.tokens_per_second,
            metrics_source=llm_result.metrics_source,
            raw_llm_result=llm_result,
        )

